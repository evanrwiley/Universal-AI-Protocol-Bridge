import type { ProtocolId } from '../canonical/types.js';

export type { ProtocolId };

export type ProviderId =
  | 'anthropic'
  | 'openai'
  | 'deepseek'
  | 'groq'
  | 'nvidia'
  | 'gemini'
  | 'bedrock'
  | 'azure'
  | 'ollama'
  | 'cohere'
  | 'mistral'
  | 'custom';

export type EndpointMode = 'translate' | 'passthrough' | 'auto';

// ── Authentication ────────────────────────────────────────────────────────────

export type ProtocolAuth =
  | { type: 'bearer'; token: string; keys?: string[] }
  | { type: 'x-api-key'; key: string; keys?: string[] }
  | { type: 'aws'; accessKeyId: string; secretAccessKey: string; sessionToken?: string; region: string }
  | { type: 'azure'; apiKey: string; apiVersion: string }
  | { type: 'multiKey'; keys: string[] }
  | { type: 'none' };

// ── Proxy Config (embedded in encrypted URL token) ────────────────────────────

export interface ProxyConfig {
  version: 1;
  sourceProtocol: ProtocolId;
  targetProtocol: ProtocolId;
  targetBaseUrl: string;
  auth: ProtocolAuth;
  modelMap?: Record<string, string>;
  forceModel?: string;
}

// ── Proxy Config v2 (generated by the new console) ───────────────────────────

export interface ProxyModelConfig {
  mode: 'passThrough' | 'map' | 'force';
  map?: Record<string, string>;
  force?: string;
  stripClientSuffix: boolean;
}

export interface ProxyEndpointConfig {
  mode: EndpointMode;
}

export interface ProxyConfigV2 {
  version: 2;
  source: {
    protocol: ProtocolId;
    provider?: ProviderId;
  };
  target: {
    protocol: ProtocolId;
    provider: ProviderId;
    baseUrl: string;
    auth: ProtocolAuth;
    apiVersion?: string;
    region?: string;
  };
  model: ProxyModelConfig;
  endpoints: ProxyEndpointConfig;
}

export type ProxyConfigInput = ProxyConfig | ProxyConfigV2;

export interface NormalizedProxyConfig extends ProxyConfig {
  provider: ProviderId;
  sourceProvider?: ProviderId;
  model: ProxyModelConfig;
  endpoints: ProxyEndpointConfig;
}

// ── Cloudflare Worker Env ─────────────────────────────────────────────────────

export interface Env {
  WORKER_SECRET: string;
  ASSETS?: Fetcher;
  SENTRY_DSN?: string; // optional Sentry error monitoring DSN
}
